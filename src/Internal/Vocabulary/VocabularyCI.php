    public function resolvePrefixedUnit(string $prefixedAtom): ?Unit {
        for ($i = min(4, strlen($prefixedAtom)); --$i;) {
            $prefix = substr($prefixedAtom, 0, $i);
            $atom = substr($prefixedAtom, $i);

            $factor = $this->_resolvePrefix($prefix);
            $unit = $this->_resolveMetricUnit($atom, $prefix);

            if ($factor && $unit) {
                return $unit->multiplyBy(new Unit([], [], [], $factor[0], $factor[1]));
            }
        }

        return null;
    }

    public function resolveUnit(string $atom): ?Unit {
        return $this->_resolveMetricUnit($atom, null) ?? $this->_resolveNonMetricUnit($atom);
    }

